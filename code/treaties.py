def key(a, b):
    return "-".join(sorted((a, b)))


def match(seg):
    """The table entry for a straight segment, or None."""
    k = key(seg["a"], seg["b"])
    cands = [t for t in T if t["k"] == k]
    for t in cands:
        s = t.get("sel")
        if s is None:
            continue
        if s[0] == "box":
            x, y = seg["mid"]
            if s[1] <= x <= s[2] and s[3] <= y <= s[4]:
                return t
        elif seg["kind"] == s[0] and s[1] <= seg["val"] <= s[2]:
            return t
    for t in cands:
        if t.get("sel") is None:
            return t
    return None
